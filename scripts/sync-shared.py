#!/usr/bin/env python3
"""Copy the shared Nagent texts into each client package.

One source of truth per text:

  plugins/nagent/skills/nagent-api/   the nagent-api skill (Claude plugin)
  shared/nagent-setup.md              setup steps for Codex and Cursor
  shared/nagent-run.md                run steps for Codex and Cursor
  plugins/nagent/.claude-plugin/icon.png and LICENSE

Every other copy is generated by this script. Edit a source, then run:

  python3 scripts/sync-shared.py          write the copies
  python3 scripts/sync-shared.py --check  exit 1 if any copy is out of date

Standard library only, Python 3.9+.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ICON = ROOT / "plugins/nagent/.claude-plugin/icon.png"
CODEX = ROOT / "codex/plugins/nagent"
CURSOR = ROOT / "cursor/plugins/nagent"


def note(source):
    return (
        f"<!-- Generated from {source} by scripts/sync-shared.py. "
        "Edit the source, not this file. -->\n\n"
    )


def split_frontmatter(text):
    if not text.startswith("---\n"):
        raise SystemExit("expected YAML frontmatter")
    end = text.index("\n---\n", 4)
    return text[4:end], text[end + 5:].lstrip("\n")


def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8")


SETUP_DESC = (
    "Set up Nagent: connect this agent to the Nagent MCP server with OAuth, "
    "list the Nagent agents it can reach, and optionally wire the Nagent SDK, "
    "an example and a webhook receiver into the current project. Use when the "
    "developer asks to set up, connect or install Nagent."
)
RUN_DESC = (
    "Run one of the developer's Nagent agents over MCP and show the result. "
    "Use when the developer asks to run or ask a named Nagent agent, for "
    "example \"run nora research retail-1.example\"."
)
RULE_DESC = (
    "Use when writing code that calls Nagent agents, approvals, knowledge, "
    "leads or triggers through the Nagent REST API (/api/v1), the "
    "@nagent/sdk (TypeScript) or nagent (Python) client, or when building a "
    "receiver for Nagent webhooks."
)

SKILL_REF_LINE = "Endpoint list: `reference.md` next to\nthis file."
RULE_REF_LINE = "Endpoint list: at the end of this rule."


def text_outputs():
    skill = read("plugins/nagent/skills/nagent-api/SKILL.md")
    reference = read("plugins/nagent/skills/nagent-api/reference.md")
    setup = read("shared/nagent-setup.md")
    run = read("shared/nagent-run.md")
    _, skill_body = split_frontmatter(skill)
    if SKILL_REF_LINE not in skill_body:
        raise SystemExit("SKILL.md no longer names reference.md as expected; update RULE text")

    out = {}

    # Codex and ChatGPT: the portable Agent Plugins package.
    out[CODEX / "skills/nagent-api/SKILL.md"] = skill
    out[CODEX / "skills/nagent-api/reference.md"] = reference
    out[CODEX / "skills/nagent-setup/SKILL.md"] = (
        f"---\nname: nagent-setup\ndescription: {json.dumps(SETUP_DESC)}\n---\n\n"
        + note("shared/nagent-setup.md") + setup
    )
    out[CODEX / "skills/nagent-run/SKILL.md"] = (
        f"---\nname: nagent-run\ndescription: {json.dumps(RUN_DESC)}\n---\n\n"
        + note("shared/nagent-run.md") + run
    )

    # Cursor: one rule for the API guidance, two commands.
    out[CURSOR / "rules/nagent-api.mdc"] = (
        f"---\ndescription: {json.dumps(RULE_DESC)}\nalwaysApply: false\n---\n\n"
        + note("plugins/nagent/skills/nagent-api/SKILL.md and reference.md")
        + skill_body.replace(SKILL_REF_LINE, RULE_REF_LINE).rstrip("\n")
        + "\n\n"
        + reference.replace("# Nagent REST API v1: endpoints", "## Endpoints", 1)
    )
    out[CURSOR / "commands/nagent-setup.md"] = (
        f"---\nname: nagent-setup\ndescription: {json.dumps(SETUP_DESC)}\n---\n\n"
        + note("shared/nagent-setup.md") + setup
    )
    out[CURSOR / "commands/nagent-run.md"] = (
        f"---\nname: nagent-run\ndescription: {json.dumps(RUN_DESC)}\n---\n\n"
        + note("shared/nagent-run.md") + run
    )
    return out


def binary_outputs():
    icon = ICON.read_bytes()
    licence = (ROOT / "LICENSE").read_bytes()
    return {
        CODEX / "assets/icon.png": icon,
        CURSOR / "assets/logo.png": icon,
        CODEX / "LICENSE": licence,
        CURSOR / "LICENSE": licence,
    }


def main(argv):
    check = "--check" in argv
    stale = []
    for path, text in text_outputs().items():
        data = text.encode("utf-8")
        if not path.exists() or path.read_bytes() != data:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    for path, data in binary_outputs().items():
        if not path.exists() or path.read_bytes() != data:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    for path in stale:
        print(("out of date: " if check else "wrote: ") + str(path.relative_to(ROOT)))
    if check and stale:
        print("Run: python3 scripts/sync-shared.py")
        return 1
    if not stale:
        print("All copies up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
